"""Generates Data/Starts.lua and Data/NewItems.lua from the game's own item tables on wago.tools.

Starts.lua: items that begin a quest when used (ItemSparse.StartQuestID of WoW: Forever).
NewItems.lua: items Forever has that original Classic (1.13.7) did not, as runs of item IDs.

Run after a client patch: python tests/build_data.py [forever-build]
"""
import csv
import io
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOREVER_BUILD = "1.60.1.70245"
CLASSIC_BUILD = "1.13.7.38704"  # the last original Classic build
URL = "https://wago.tools/db2/{table}/csv?build={build}"


def fetch(table, build):
    # wago.tools refuses Python's default user agent
    request = urllib.request.Request(URL.format(table=table, build=build), headers={"User-Agent": "KeepOrSell-build-data"})
    with urllib.request.urlopen(request) as response:
        return list(csv.DictReader(io.StringIO(response.read().decode("utf-8"))))


def runs(ids):
    """Sorted IDs as [first, last] runs of consecutive numbers."""
    result = []
    for i in sorted(ids):
        if result and result[-1][1] == i - 1:
            result[-1][1] = i
        else:
            result.append([i, i])
    return result


def rows_of(numbers, per_line):
    return "\n".join("  " + ", ".join(str(n) for n in numbers[i:i + per_line]) + ","
                     for i in range(0, len(numbers), per_line))


def main(build=FOREVER_BUILD):
    sparse = fetch("ItemSparse", build)
    classic = {int(r["ID"]) for r in fetch("Item", CLASSIC_BUILD)}
    starts = sorted((int(r["ID"]), int(r["StartQuestID"])) for r in sparse if r["StartQuestID"] not in ("", "0"))
    new = runs(int(r["ID"]) for r in sparse if int(r["ID"]) not in classic)

    header = "-- GENERATED by tests/build_data.py from WoW: Forever build %s. Do not edit.\nlocal _, ns = ...\n\n" % build
    (ROOT / "Data" / "Starts.lua").write_text(
        header
        + "-- Items that begin a quest when used, from the game's own item table; QuestieDB may not know\n"
        + "-- every one Forever added. itemID -> questID\n"
        + "ns.STARTS_QUEST = {\n"
        + "\n".join("  [%d] = %d," % pair for pair in starts)
        + "\n}\n", encoding="utf-8", newline="\n")
    (ROOT / "Data" / "NewItems.lua").write_text(
        header
        + "-- Items original Classic (build %s) did not have, as runs of item IDs: first, last, first, last ...\n"
          % CLASSIC_BUILD
        + "ns.NEW_ITEM_RUNS = {\n"
        + rows_of([n for run in new for n in run], 12)
        + "\n}\n", encoding="utf-8", newline="\n")
    print("%d quest starters, %d new item runs" % (len(starts), len(new)))


if __name__ == "__main__":
    main(*sys.argv[1:])
